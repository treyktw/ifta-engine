const SAMPLE_INTERVAL_MS = 30_000;
const SPEED_MPH = 62;
// 2026-04-14 06:00 Central (11:00 UTC) — inside the 2026-Q2 rate period.
const START_MS = Date.UTC(2026, 3, 14, 11, 0, 0);

function round(value: number, digits: number): number {
  const factor = 10 ** digits;
  return Math.round(value * factor) / factor;
}

export function generateTrace(): TrackPoint[] {
  const points: TrackPoint[] = [];
  let clock = START_MS;
  const milesPerSample = (SPEED_MPH * SAMPLE_INTERVAL_MS) / 3_600_000;

  points.push({ lat: ROUTE[0].lat, lng: ROUTE[0].lng, recordedAt: clock });

  for (let i = 1; i < ROUTE.length; i++) {
    const from = ROUTE[i - 1];
    const to = ROUTE[i];
    const legMiles = haversineMiles(from.lat, from.lng, to.lat, to.lng);
    const steps = Math.max(1, Math.ceil(legMiles / milesPerSample));
    for (let step = 1; step <= steps; step++) {
      const t = step / steps;
      clock += SAMPLE_INTERVAL_MS;
      points.push({
        lat: round(from.lat + (to.lat - from.lat) * t, 5),
        lng: round(from.lng + (to.lng - from.lng) * t, 5),
        recordedAt: clock,
      });
    }
    // Parked: the phone keeps reporting the same fix. Sampled every 5 min so
    // the file stays small; the engine drops them as zero-distance segments.
    if (to.stopMinutes) {
      for (let minute = 5; minute <= to.stopMinutes; minute += 5) {
        points.push({ lat: round(to.lat, 5), lng: round(to.lng, 5), recordedAt: clock + minute * 60_000 });
      }
      clock += to.stopMinutes * 60_000;
    }
  }
  return points;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.dirname, "generate-trace.ts");
if (isMain) {
  const trace = generateTrace();
  const out = resolve(import.meta.dirname, "../data/traces/dallas-to-cincinnati.json");
  writeFileSync(
    out,
    `{\n  "description": "SYNTHETIC GPS trace for demos and tests. Dallas TX -> I-20 -> Atlanta GA -> I-75 -> Cincinnati OH. Generated by scripts/generate-trace.ts; not a real vehicle.",\n  "points": [\n${trace
      .map((p) => `    ${JSON.stringify(p)}`)
      .join(",\n")}\n  ]\n}\n`,
  );
  console.log(`wrote ${trace.length} points to ${out}`);
}
