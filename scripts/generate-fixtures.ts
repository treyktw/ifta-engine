/**
 * Regenerates fixtures/attribution-boundaries-v1.json from the TypeScript engine.
 *
 * The TypeScript engine is the reference implementation; this fixture pins its
 * output on a real-world boundary file and the synthetic multi-state trace so
 * that (a) the TS tests catch regressions and (b) the Rust tests prove the port
 * computes the same miles, to floating-point tolerance, from the same inputs.
 *
 * Only rerun after an intentional behaviour change, and review the diff.
 *
 *   pnpm generate:fixtures
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { attributeTrackToJurisdictions, pointInJurisdiction } from "../src/attribute";
import { parseGeoJsonDataset } from "../src/dataset";
import type { TrackPoint } from "../src/types";

const root = resolve(import.meta.dirname, "..");
const boundaryPath = "data/boundaries/us-ca-admin1.geojson";
const tracePath = "data/traces/dallas-to-cincinnati.json";

const dataset = parseGeoJsonDataset(JSON.parse(readFileSync(resolve(root, boundaryPath), "utf8")));
const trace = JSON.parse(readFileSync(resolve(root, tracePath), "utf8")) as { points: TrackPoint[] };
const result = attributeTrackToJurisdictions(trace.points, dataset);

// Probe points: city centres, one per jurisdiction family, plus open water.
const probes: Array<{ name: string; lat: number; lng: number }> = [
  { name: "Atlanta", lat: 33.749, lng: -84.388 },
  { name: "Dallas", lat: 32.7767, lng: -96.797 },
  { name: "Shreveport", lat: 32.5252, lng: -93.7502 },
  { name: "Denver", lat: 39.7392, lng: -104.9903 },
  { name: "Toronto", lat: 43.6532, lng: -79.3832 },
  { name: "Montreal", lat: 45.5017, lng: -73.5673 },
  { name: "Vancouver", lat: 49.2827, lng: -123.1207 },
  { name: "Honolulu", lat: 21.3069, lng: -157.8583 },
  { name: "Gulf of Mexico", lat: 26.0, lng: -90.0 },
  { name: "Atlantic Ocean", lat: 35.0, lng: -60.0 },
];

const fixture = {
  description:
    "Generated by scripts/generate-fixtures.ts from the TypeScript engine. Rust must match: same jurisdiction codes, miles within milesTolerance.",
  boundaryPath,
  tracePath,
  milesTolerance: 1e-6,
  datasetCodes: dataset.map((j) => j.code).sort(),
  expected: {
    totalMiles: result.totalMiles,
    unattributedMiles: result.unattributedMiles,
    byJurisdiction: [...result.byJurisdiction].sort((a, b) =>
      a.jurisdiction.localeCompare(b.jurisdiction),
    ),
  },
  probes: probes.map((p) => ({ ...p, expected: pointInJurisdiction(p.lat, p.lng, dataset) })),
};

writeFileSync(resolve(root, "fixtures/attribution-boundaries-v1.json"), `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote fixtures/attribution-boundaries-v1.json (${result.byJurisdiction.length} jurisdictions, ${result.totalMiles.toFixed(1)} mi)`);
